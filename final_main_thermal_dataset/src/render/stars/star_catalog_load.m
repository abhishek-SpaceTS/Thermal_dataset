function catalog = star_catalog_load(filepath, mag_limit)
% Load the Hipparcos/Tycho catalog into a fixed-column matrix.

persistent cache
if isempty(cache)
    cache = containers.Map('KeyType', 'char', 'ValueType', 'any');
end
cache_key = sprintf('%s|%.6f', filepath, mag_limit);
if isKey(cache, cache_key)
    catalog = cache(cache_key);
    return;
end

if ~isfile(filepath)
    error('star_catalog_load:notFound', ...
          'Catalog not found: %s', filepath);
end

col_map = { ...
    'HIP',      1; ...
    'RAICRS',   2; ...
    'DEICRS',   3; ...
    'Vmag',     4; ...
    'e_RAICRS', 5; ...
    'e_DEICRS', 6; ...
    'Plx',      7; ...
    'e_Plx',    8; ...
    'pmRA',     9; ...
    'pmDE',     10; ...
    'e_pmRA',   11; ...
    'e_pmDE',   12; ...
    'BTmag',    13; ...
    'e_BTmag',  14; ...
    'VTmag',    15; ...
    'e_VTmag',  16; ...
    'B-V',      17; ...
    'e_B-V',    18; ...
    'V-I',      19; ...
    'e_V-I',    20; ...
    'Hpmag',    21; ...
    'e_Hpmag',  22; ...
    'Hpscat',   23; ...
    'Hpmax',    24; ...
    'HPmin',    25};

t = readtable(filepath, 'VariableNamingRule', 'preserve');
var_names = t.Properties.VariableNames;

cols = star_columns();
num_rows = height(t);
catalog_full = zeros(num_rows, 25);

for k = 1:size(col_map, 1)
    name = col_map{k, 1};
    idx  = col_map{k, 2};
    if any(strcmp(var_names, name))
        col = t.(name);
        if iscell(col) || isstring(col)
            col = str2double(col);
        end
        catalog_full(:, idx) = double(col);
    end
end

mag_col   = catalog_full(:, cols.MAG);
keep_rows = ~isnan(mag_col) & mag_col <= mag_limit;
catalog   = catalog_full(keep_rows, :);

catalog(isnan(catalog)) = 0.0;

if isempty(catalog)
    error('star_catalog_load:empty', ...
          'No stars loaded from %s (mag_limit=%.2f).', filepath, mag_limit);
end

cache(cache_key) = catalog;

end
